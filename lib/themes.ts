export function getThemes(): ShopifyTheme[] {
  return SHOPIFY_THEMES;
}

export function getAllProducts(): ShopifyTheme[] {
  return SHOPIFY_THEMES;
}

export function getShopifyThemes(): ShopifyTheme[] {
  return SHOPIFY_THEMES.filter(t => !t.category || t.category === 'shopify');
}

export function getWebsites(): ShopifyTheme[] {
  return SHOPIFY_THEMES.filter(t => t.category === 'website');
}

export function getThemeBySlug(slug: string): ShopifyTheme | undefined {
  return SHOPIFY_THEMES.find(t => t.slug.toLowerCase() === slug.toLowerCase());
}
